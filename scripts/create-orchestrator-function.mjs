async function ensureResultsDatabaseCollections(databaseId) {
  const list = await api.get(`/databases/${encodeURIComponent(databaseId)}/collections`);
  const collections = Array.isArray(list.collections) ? list.collections : [];
  const existingNames = new Set(collections.map((entry) => String(entry?.name || '').toLowerCase()));
  for (const spec of getResultsDatabaseCollectionSpecs()) {
    if (existingNames.has(spec.name.toLowerCase())) continue;
    await api.post(`/databases/${encodeURIComponent(databaseId)}/collections`, spec);
    console.log(`Created database collection ${spec.name}`);
  }
}

async function upsertSecret(serverId, name, value, options = {}) {
  const list = await api.get(`/servers/${encodeURIComponent(serverId)}/secrets`);
  const secrets = Array.isArray(list.secrets) ? list.secrets : Array.isArray(list.data) ? list.data : [];
  const existing = secrets.find((secret) => String(secret?.name || '').toLowerCase() === String(name).toLowerCase());
  const payload = {
    name,
    value,
    description: options.description || '',
    metadata: options.metadata || null,
  };
  if (existing?.id) {
    await api.put(`/servers/${encodeURIComponent(serverId)}/secrets/${encodeURIComponent(existing.id)}`, payload);
    console.log(`Updated secret ${name}`);
    return;
  }
  await api.post(`/servers/${encodeURIComponent(serverId)}/secrets`, payload);
  console.log(`Created secret ${name}`);
}

