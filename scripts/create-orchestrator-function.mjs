async function uploadSourceFile(serverId, filePath, content) {
  const encodedPath = filePath.split('/').map((part) => encodeURIComponent(part)).join('/');
  await api.put(`/servers/${encodeURIComponent(serverId)}/files/content/${encodedPath}`, { content });
  console.log(`Uploaded ${filePath}`);
}

function createApiClient(input) {
  const baseUrl = input.baseUrl.replace(/\/+$/, '');
  const headers = {
    authorization: `Bearer ${input.apiKey}`,
    'x-api-key': input.apiKey,
    'content-type': 'application/json',
  };

  async function request(method, path, body) {
    const response = await fetch(`${baseUrl}${path}`, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    const text = await response.text();
    let payload;
    try {
      payload = text ? JSON.parse(text) : {};
    } catch {
      payload = { text };
    }
    if (!response.ok) {
      const message = payload?.message || payload?.error || response.statusText || 'Request failed';
      throw new Error(`${method} ${path} failed (${response.status}): ${message}`);
    }
    return payload;
  }

  return {
    get: (path) => request('GET', path),
    post: (path, body) => request('POST', path, body),
    put: (path, body) => request('PUT', path, body),
    patch: (path, body) => request('PATCH', path, body),
    delete: (path) => request('DELETE', path),
  };
}

function readEnv(name) {
  const value = process.env[name];
  return typeof value === 'string' ? value.trim() : '';
}

function readBoolean(value, fallback) {
  if (!value) return fallback;
  if (/^(1|true|yes|on)$/i.test(value)) return true;
  if (/^(0|false|no|off)$/i.test(value)) return false;
  return fallback;
}

function loadDotEnv(path) {
  let content = '';
  try {
    content = readFileSync(path, 'utf8');
  } catch {
    return;
  }
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index < 0) continue;
    const key = trimmed.slice(0, index).trim();
    const rawValue = trimmed.slice(index + 1).trim();
    if (!key || process.env[key] !== undefined) continue;
    process.env[key] = rawValue.replace(/^(['"])(.*)\1$/, '$2');
  }
}
