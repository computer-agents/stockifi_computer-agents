async function findOrCreateSecretsServer() {
  if (config.secretsServerId) {
    const response = await api.get(`/servers/${encodeURIComponent(config.secretsServerId)}`);
    const existing = response.server;
    if (!existing) throw new Error(`Secrets server ${config.secretsServerId} was not found.`);
    if (existing.kind !== 'secrets') throw new Error(`Server ${config.secretsServerId} is not a secrets vault.`);
    await api.patch(`/servers/${encodeURIComponent(existing.id)}`, buildSecretsServerPatch(existing));
    return { ...existing, ...buildSecretsServerPatch(existing) };
  }

  const list = await api.get('/servers?limit=200');
  const servers = Array.isArray(list.servers) ? list.servers : Array.isArray(list.data) ? list.data : [];
  const existing = servers.find((item) => item?.kind === 'secrets' && item?.name === config.secretsName);
  if (existing) {
    await api.patch(`/servers/${encodeURIComponent(existing.id)}`, buildSecretsServerPatch(existing));
    return { ...existing, ...buildSecretsServerPatch(existing) };
  }

  const created = await api.post('/servers', {
    name: config.secretsName,
    description: 'Secrets vault for the Stockifi menu validation workflow.',
    kind: 'secrets',
    sourceType: 'manual',
    sourcePath: null,
    projectId: config.projectId || null,
    region: config.region,
    runtime: '',
    authMode: 'private',
    status: 'deployed',
    metadata: {
      owner: 'stockifi',
      purpose: 'stockifi-menu-validation',
      managedBy: 'stockifi-computer-agents-validation-workflow',
      secretVault: { documents: [] },
    },
  });

  if (!created.server?.id) throw new Error('Create secrets server response did not include server.id.');
  return created.server;
}

function buildSecretsServerPatch(existing) {
  return {
    name: config.secretsName,
    description: existing.description || 'Secrets vault for the Stockifi menu validation workflow.',
    kind: 'secrets',
    sourceType: 'manual',
    sourcePath: null,
    region: config.region,
    authMode: 'private',
    metadata: {
      ...(existing.metadata && typeof existing.metadata === 'object' && !Array.isArray(existing.metadata) ? existing.metadata : {}),
      owner: 'stockifi',
      purpose: 'stockifi-menu-validation',
      managedBy: 'stockifi-computer-agents-validation-workflow',
    },
  };
}

